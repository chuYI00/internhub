def generate(target: str = DEFAULT_TARGET, role: str = "", exam_date: str = "",
             hours: int = 6, today=None) -> dict:
    """生成一份完整备考方案（结构化 dict）。"""
    p = profile_of(target)
    rk = role_key_of(target, role)
    n = days_left(exam_date, today)
    st = stages(n)
    dtable, dtotal = daily_schedule(hours, rk, sprint=(0 < n <= 21))
    mem = p.get("memorize") or {}
    return {
        "target": target if target in _PROFILES else (p["short"] if target else p["short"]),
        "target_raw": target or p["short"],
        "short": p["short"],
        "role": role or "（未填，按你专业默认走计算机/信息方向）",
        "role_key": rk,
        "exam_date": exam_date or "（未填）",
        "days_left": n,
        "hours_per_day": max(1, int(hours or 6)),
        "total_hours": max(0, n) * max(1, int(hours or 6)),
        "note": p.get("note", ""),
        "exam_note": p.get("exam_note", ""),
        "subjects": p.get("subjects") or [],
        "priority": p.get("priority") or [],
        "stages": st,
        "schedule": dtable,
        "schedule_total": dtotal,
        "memorize": mem,
        "sources": p.get("sources") or [],
        "generated_at": datetime.now().strftime("%Y-%m-%d %H:%M"),
    }


