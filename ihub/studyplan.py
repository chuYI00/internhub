def daily_schedule(hours: int, role_key: str, sprint: bool = False) -> tuple:
    """每日时间表：([(时段, 干什么, 时长)], 总量小时)。

    总量只会落在设定值附近（少 ≤0.6h，多 ≤1.5h）——排太满的方案一定执行不下去，
    与其每天欠账，不如一开始就按真实能给的时间排。
    """
    h = max(1, min(int(hours or 4), 12))
    base = next(t for lo, t in _SCHEDULE_TIERS if h >= lo)
    table = [(slot, task.format(rk=role_key), dur) for slot, task, dur in base]

    # 冲刺期一定要有一块「整卷/限时训练」——那是冲刺阶段唯一有效的动作
    if sprint and not any(("整卷" in t or "限时训练" in t) for _, t, _ in table):
        table.append(("机动 60 分钟", "整卷计时（按考试时间做完整套）", 1.0))

    # 给的时长比课表长 → 补机动块，别让课表明显短于设定
    i = 0
    while sum(x[2] for x in table) < h - 1.0 and i < len(_SCHEDULE_EXTRA):
        table.append(_SCHEDULE_EXTRA[i])
        i += 1

    total = sum(x[2] for x in table)
    return table, round(total, 2)


