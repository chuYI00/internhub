def out_dir() -> str:
    d = os.path.join(config.PROJECT_ROOT, "备考冲刺资料")
    os.makedirs(d, exist_ok=True)
    return d


def _safe_name(s: str) -> str:
    return re.sub(r'[\\/:*?"<>|]', "_", str(s or "")).strip()[:40]


def save_markdown(plan: dict, path: str = None) -> str:
    path = path or os.path.join(out_dir(), f'备考方案_{_safe_name(plan["short"])}.md')
    with open(path, "w", encoding="utf-8") as f:
        f.write(to_markdown(plan))
    return path


def save_docx(plan: dict, md_path: str = None) -> str:
    """导出 Word（走项目已有的 md2docx，失败不抛错，返回空串）。"""
    try:
        from . import md2docx
        md_path = md_path or save_markdown(plan)
        docx_path = os.path.splitext(md_path)[0] + ".docx"
        md2docx.build(md_path, docx_path)
        return docx_path
    except Exception:
        return ""


def default_exam_date(short: str, today=None) -> str:
    """给个合理的默认考试日（用户不改也能出方案）。用上一年公告节奏估。"""
    t = today or date.today()
    guess = {
        "云南省烟草专卖局": (12, 6),
        "云南中烟": (12, 6),
        "南方电网": (12, 8),
        "云南航产投": (11, 15),
        "银行": (11, 8),
        "央国企": (11, 20),
    }
    m, d = guess.get(short, (11, 20))
    y = t.year if (m, d) >= (t.month, t.day) else t.year + 1
    try:
        return date(y, m, d).isoformat()
    except ValueError:
        return (t + timedelta(days=90)).isoformat()
