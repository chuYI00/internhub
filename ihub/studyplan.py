def profile_of(target: str) -> dict:
    """按名字/别名找档案；找不到就用通用档案（并保留原名）。

    取「命中的最长别名」—— 否则「云南烟草中烟」会先撞上更短的「烟草」，
    被配到专卖局那一套考情去。思路与 channels.official_for() 一致。
    """
    if target in _PROFILES:
        return _PROFILES[target]
    t = str(target or "")
    best_name, best_len = "", 0
    for name, p in _PROFILES.items():
        for a in p.get("alias", []):
            if a and a in t and len(a) > best_len:
                best_name, best_len = name, len(a)
    return _PROFILES[best_name] if best_name else _PROFILES[DEFAULT_TARGET]


def role_key_of(target: str, role: str) -> str:
    """把用户填的岗位名映射到三套专业清单之一。"""
    p = profile_of(target)
    r = str(role or "")
    for kw, key in (p.get("role_hint") or {}).items():
        if kw and kw in r:
            return key
    for key in ("电气/自动化", "机械", "计算机/信息"):
        if any(w in r for w in key.split("/")):
            return key
    return "计算机/信息"          # 电子信息/物联网默认走计算机信息那一套


