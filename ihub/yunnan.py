def by_cat():
    out = {}
    for u in UNITS:
        out.setdefault(u["cat"], []).append(u)
    return out


def cats_in_order():
    out = by_cat()
    return [(c, out[c]) for c in CATS if c in out]


def for_me():
    """按"物联网 / 电子信息与自动化"专业契合度排序（★★★★ 及以上）。"""
    ok = [u for u in UNITS if u["heat"].startswith("★★★★")]
    return sorted(ok, key=lambda u: -u["heat"].count("★"))


def as_text() -> str:
    L = ["云南秋招投递渠道地图（昆明 / 大理）", "=" * 60, ""]
    for cat, items in cats_in_order():
        L.append(cat)
        L.append("-" * 50)
        for u in items:
            L.append(f'【{u["name"]}】契合度 {u["heat"]}')
            for what, url in official_links(u):
                L.append(f"  ✅ {what}（官方直达）：{url}")
            if not has_official(u):
                L.append("  ✅ 官方直达：—（该单位没有独立网申页，走上级/公众号统一发布）")
            if u["apply_note"]:
                L.append("  说明：" + u["apply_note"])
            L.append("  🔎 搜索兜底（点开是搜索引擎，不是直达）：" + u["search"])
            L.append("  对口岗位：" + u["fit"])
            L.append("  招聘节奏：" + u["rhythm"])
            L.append("  提醒：" + u["tips"])
            L.append("")
    L.append("每周固定动作")
    L.append("-" * 50)
    for d, task, url in WEEKLY:
        L.append(f"{d}：{task}" + (f"　{url}" if url else ""))
    L.append("")
    L.append("链接质量说明（《重构指令》第 2 步）：")
    L.append("  · 「官方直达」＝ 该单位自己的域名，可直接当投递入口；")
